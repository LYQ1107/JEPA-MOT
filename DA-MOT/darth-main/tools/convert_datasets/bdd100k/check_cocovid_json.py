"""Check CocoVID format JSON for correctness and visualize samples.

Validates the structure and referential integrity of a CocoVID annotation file
generated by convert_bdd_weather_to_cocovid.py.
"""
import argparse
import json
import os
import os.path as osp
import random
from collections import defaultdict

import numpy as np
from PIL import Image, ImageDraw, ImageFont


def parse_args():
    parser = argparse.ArgumentParser(
        description='Check CocoVID JSON for correctness.')
    parser.add_argument('--json-file', type=str, required=True,
                        help='Path to CocoVID JSON file')
    parser.add_argument('--img-prefix', type=str, required=True,
                        help='Image prefix directory')
    parser.add_argument('--vis-dir', type=str,
                        default='work_dirs/debug_bdd_da_vis/',
                        help='Directory to save visualizations')
    parser.add_argument('--num-vis', type=int, default=10,
                        help='Number of images to visualize')
    parser.add_argument('--seed', type=int, default=42)
    return parser.parse_args()


def check_cocovid(json_file, img_prefix, vis_dir=None, num_vis=10, seed=42):
    print(f"Checking: {json_file}")
    print(f"Image prefix: {img_prefix}")
    print(f"{'='*60}")

    with open(json_file, 'r') as f:
        data = json.load(f)

    errors = []
    warnings = []

    for key in ['videos', 'images', 'annotations', 'categories']:
        if key not in data:
            errors.append(f"Missing top-level key: {key}")
    if errors:
        print("ERRORS:")
        for e in errors:
            print(f"  - {e}")
        return False

    videos = data['videos']
    images = data['images']
    annotations = data['annotations']
    categories = data['categories']

    print(f"Videos: {len(videos)}")
    print(f"Images: {len(images)}")
    print(f"Annotations: {len(annotations)}")
    print(f"Categories: {len(categories)}")
    print()

    video_ids = set()
    for v in videos:
        if v['id'] in video_ids:
            errors.append(f"Duplicate video id: {v['id']}")
        video_ids.add(v['id'])

    image_ids = set()
    image_id_to_img = {}
    for img in images:
        if img['id'] in image_ids:
            errors.append(f"Duplicate image id: {img['id']}")
        image_ids.add(img['id'])
        image_id_to_img[img['id']] = img
        if img.get('video_id') not in video_ids:
            errors.append(
                f"Image {img['id']} references invalid video_id: "
                f"{img.get('video_id')}")

    cat_ids = {c['id'] for c in categories}
    cat_id_to_name = {c['id']: c['name'] for c in categories}

    cat_counts = defaultdict(int)
    instance_ids_seen = set()
    for ann in annotations:
        if ann.get('image_id') not in image_ids:
            errors.append(
                f"Annotation {ann['id']} references invalid image_id: "
                f"{ann.get('image_id')}")
        if ann.get('video_id') not in video_ids:
            errors.append(
                f"Annotation {ann['id']} references invalid video_id: "
                f"{ann.get('video_id')}")
        if ann.get('category_id') not in cat_ids:
            errors.append(
                f"Annotation {ann['id']} has invalid category_id: "
                f"{ann.get('category_id')}")
        if 'instance_id' not in ann:
            errors.append(f"Annotation {ann['id']} missing instance_id")
        else:
            instance_ids_seen.add(ann['instance_id'])

        cat_counts[ann.get('category_id', -1)] += 1

    print("Category distribution:")
    for cat_id in sorted(cat_counts.keys()):
        name = cat_id_to_name.get(cat_id, 'UNKNOWN')
        print(f"  {name} (id={cat_id}): {cat_counts[cat_id]}")
    print(f"\nUnique instances: {len(instance_ids_seen)}")

    random.seed(seed)
    sample_images = random.sample(images, min(5, len(images)))
    readable = 0
    for img in sample_images:
        path = osp.join(img_prefix, img['file_name'])
        if osp.exists(path):
            try:
                with Image.open(path) as pil_img:
                    _ = pil_img.size
                readable += 1
            except Exception as e:
                warnings.append(f"Cannot read image {path}: {e}")
        else:
            warnings.append(f"Image not found: {path}")
    print(f"\nImage readability check: {readable}/{len(sample_images)} OK")

    if errors:
        print(f"\nERRORS ({len(errors)}):")
        for e in errors[:20]:
            print(f"  - {e}")
        if len(errors) > 20:
            print(f"  ... and {len(errors) - 20} more")
    else:
        print("\nNo errors found.")

    if warnings:
        print(f"\nWARNINGS ({len(warnings)}):")
        for w in warnings[:10]:
            print(f"  - {w}")

    if vis_dir and len(images) > 0:
        os.makedirs(vis_dir, exist_ok=True)
        img_to_anns = defaultdict(list)
        for ann in annotations:
            img_to_anns[ann['image_id']].append(ann)

        vis_images = random.sample(images, min(num_vis, len(images)))
        colors = ['red', 'blue', 'green', 'yellow', 'cyan', 'magenta',
                  'orange', 'purple', 'pink', 'brown']

        for idx, img_info in enumerate(vis_images):
            path = osp.join(img_prefix, img_info['file_name'])
            if not osp.exists(path):
                continue
            try:
                pil_img = Image.open(path).convert('RGB')
                draw = ImageDraw.Draw(pil_img)
                anns = img_to_anns.get(img_info['id'], [])
                for ann in anns:
                    bbox = ann['bbox']
                    x, y, w, h = bbox
                    cat_name = cat_id_to_name.get(ann['category_id'], '?')
                    inst_id = ann.get('instance_id', '?')
                    color = colors[ann['category_id'] % len(colors)]
                    draw.rectangle([x, y, x + w, y + h], outline=color,
                                   width=2)
                    label = f"{cat_name}:{inst_id}"
                    draw.text((x, max(0, y - 12)), label, fill=color)

                save_path = osp.join(vis_dir, f"vis_{idx:03d}.jpg")
                pil_img.save(save_path)
            except Exception as e:
                print(f"  Visualization failed for {path}: {e}")

        print(f"\nVisualizations saved to: {vis_dir}")

    return len(errors) == 0


def main():
    args = parse_args()
    success = check_cocovid(
        json_file=args.json_file,
        img_prefix=args.img_prefix,
        vis_dir=args.vis_dir,
        num_vis=args.num_vis,
        seed=args.seed,
    )
    if success:
        print("\nVALIDATION PASSED")
    else:
        print("\nVALIDATION FAILED")
        exit(1)


if __name__ == '__main__':
    main()
