def crop_feature(image: np.ndarray, box: Sequence[float], dim: int = 80) -> np.ndarray:
    """Small fixed teacher encoder: spatial RGB + cheap colour moments.

    This function is called for every public detection.  Keeping it free of
    per-crop histogram/percentile loops makes the smoke reproducible on a
    workstation while still retaining local appearance and colour statistics.
    """
    h, w = image.shape[:2]
    x1, y1, x2, y2 = [float(v) for v in box[:4]]
    # Include a small context ring, but keep all coordinates inside the frame.
    bw, bh = max(2.0, x2 - x1), max(2.0, y2 - y1)
    x1 = int(max(0, math.floor(x1 - 0.08 * bw)))
    y1 = int(max(0, math.floor(y1 - 0.08 * bh)))
    x2 = int(min(w, math.ceil(x2 + 0.08 * bw)))
    y2 = int(min(h, math.ceil(y2 + 0.08 * bh)))
    if x2 <= x1 or y2 <= y1:
        return np.zeros(dim, dtype=np.float32)
    crop = image[y1:y2, x1:x2]
    # The deterministic encoder is frozen for all methods.
    small = cv2.resize(crop, (4, 4), interpolation=cv2.INTER_AREA).astype(np.float32) / 255.0
    rgb = small[:, :, ::-1].reshape(-1)
    mean = crop.reshape(-1, 3).mean(axis=0).astype(np.float32) / 255.0
    std = crop.reshape(-1, 3).std(axis=0).astype(np.float32) / 255.0
    # A tiny grayscale summary is cheaper than a histogram and robust for
    # small pedestrian boxes.
    gray_mean = float(crop.mean()) / 255.0
    gray_std = float(crop.std()) / 255.0
    f = np.concatenate([rgb, mean, std, np.asarray([gray_mean, gray_std], dtype=np.float32)])
    if f.size < dim:
        f = np.pad(f, (0, dim - f.size))
    elif f.size > dim:
        f = f[:dim]
    f = f.astype(np.float32)
    f -= f.mean()
    return (f / max(float(np.linalg.norm(f)), 1e-6)).astype(np.float32)


@dataclass
class Det:
    frame: int
    box: np.ndarray  # xyxy
    score: float
    feat: Optional[np.ndarray] = None


@dataclass
class GT:
    frame: int
    gid: int
    box: np.ndarray  # xyxy
    vis: float = 1.0


def parse_mot_gt(path: Path) -> Dict[int, List[GT]]:
    out: Dict[int, List[GT]] = {}
    if not path.exists():
        return out
    for line in path.read_text(errors="replace").splitlines():
        if not line.strip():
            continue
        p = line.split(",")
        if len(p) < 6:
            continue
        try:
            fr, gid = int(float(p[0])), int(float(p[1]))
            box = xywh_to_xyxy([float(p[2]), float(p[3]), float(p[4]), float(p[5])])
            mark = float(p[6]) if len(p) > 6 else 1.0
            cls = int(float(p[7])) if len(p) > 7 else 1
            vis = float(p[8]) if len(p) > 8 else 1.0
        except (TypeError, ValueError):
            continue
        # MOT17 pedestrian benchmark convention: mark=1, class=1.
        if mark <= 0 or cls not in (1,):
            continue
        out.setdefault(fr, []).append(GT(fr, gid, box, vis))
    return out


def parse_mot_det(path: Path) -> Dict[int, List[Det]]:
    out: Dict[int, List[Det]] = {}
    if not path.exists():
        return out
    for line in path.read_text(errors="replace").splitlines():
        if not line.strip():
            continue
        p = line.split(",")
        if len(p) < 6:
            continue
        try:
            fr = int(float(p[0]))
            box = xywh_to_xyxy([float(p[2]), float(p[3]), float(p[4]), float(p[5])])
            score = float(p[6]) if len(p) > 6 else 1.0
        except (TypeError, ValueError):
            continue
        if not np.isfinite(box).all() or not np.isfinite(score):
            continue
        out.setdefault(fr, []).append(Det(fr, box, score))
    return out


def parse_frame_det_cache(seq_dir: Path, max_frames: int = 0) -> Dict[int, List[Det]]:
    """Read a D-CTRL per-frame cache (no identity column)."""
    out: Dict[int, List[Det]] = {}
    if not seq_dir.exists():
        return out
    for path in sorted(seq_dir.glob("*.txt")):
        try:
            fr = int(path.stem)
        except ValueError:
            continue
        if max_frames and fr > max_frames:
            continue
        rows: List[Det] = []
        for line in path.read_text(errors="replace").splitlines():
            p = line.strip().split(",")
            if len(p) < 6:
                continue
            try:
                # D-CTRL format: frame,x,y,w,h,score.  Ignore the repeated
                # frame field and never interpret a column as a track ID.
                box = xywh_to_xyxy([float(p[1]), float(p[2]), float(p[3]), float(p[4])])
                score = float(p[5])
            except (TypeError, ValueError):
                continue
            if np.isfinite(box).all() and np.isfinite(score):
                rows.append(Det(fr, box, score))
        out[fr] = rows
    return out


def sequence_wh(seq_dir: Path) -> Tuple[float, float]:
    """Get image dimensions without assuming MOT17's 1920x1080."""
    ini = seq_dir / "seqinfo.ini"
    if ini.exists():
        vals = {}
        for line in ini.read_text(errors="replace").splitlines():
            if "=" in line:
                k, v = line.split("=", 1); vals[k.strip()] = v.strip()
        try:
            return float(vals.get("imWidth", 0)), float(vals.get("imHeight", 0))
        except ValueError:
            pass
    fs = image_files(seq_dir)
    if fs:
        im = cv2.imread(str(fs[0]))
        if im is not None:
            return float(im.shape[1]), float(im.shape[0])
    return 1.0, 1.0


