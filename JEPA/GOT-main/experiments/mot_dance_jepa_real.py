"""A bounded, reproducible real-data MOT experiment for MOT-specific JEPA.

This is deliberately an association-only harness.  Detector boxes, the
Hungarian solver, and the track lifecycle are shared by every method.  JEPA
is used only to predict a stable track--candidate appearance representation
from a short track history and the current candidate.  The teacher is a
fixed clean-crop encoder (stop-gradient); the student predictor is trained on
train sequences with current-frame corruption and identity-negative
competition.  At evaluation time neither GT boxes/IDs nor the teacher are
used.

The harness is not intended to replace a production tracker.  It provides a
real-image, fixed-detection attribution test before integrating the predictor
into ToMP/MASA.  DanceTrack detections are generated by the locally available
YOLOX detector when requested; no tracker output is accepted as detections.
If extraction is unavailable, ``--dance-oracle`` creates an explicitly
labelled GT-box diagnostic with controlled misses/jitter.
"""

