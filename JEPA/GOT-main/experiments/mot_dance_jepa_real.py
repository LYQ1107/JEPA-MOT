    legacy_val_samples = build_jepa_samples(val_tuples, args.max_frames, args.seed + 7001, max_samples=min(args.max_samples, 12000)) if legacy_train_samples is not None else None
    val_samples = temporal_val_samples if temporal_val_samples is not None else legacy_val_samples
    if val_samples is None:
        val_samples = {"x": np.zeros((0, temporal_input_dim()), np.float32), "y": np.zeros((0, 80), np.float32)}
    validation_stats = {}
    for k, v in predictors.items():
        if v is None:
            validation_stats[k] = None
        elif isinstance(v, TemporalPredictor):
            validation_stats[k] = v.diagnostics(temporal_val_samples or val_samples)
        else:
            validation_stats[k] = v.diagnostics(legacy_val_samples or val_samples)
    all_rows = []
    seq_summaries = {}
    for seq_dir, gt, det, info in eval_items:
        seq_name = str(info["sequence"])
        seq_summaries[seq_name] = {}
        iw, ih = sequence_wh(seq_dir)
        bins = frame_bins(gt, det)
        fixed_det_recall = detector_recall(gt, det)
        det_digest_h = hashlib.sha256()
        feature_digest_h = hashlib.sha256()
        for fr0, ds0 in sorted(det.items()):
            det_digest_h.update((f"{fr0}:{len(ds0)}:" + ",".join(f"{d0.box.tolist()}:{d0.score:.6f}" for d0 in ds0)).encode())
            for d0 in ds0:
                if d0.feat is not None:
                    feature_digest_h.update(f"{fr0}:{d0.score:.6f}:".encode())
                    feature_digest_h.update(np.asarray(d0.feat, dtype=np.float32).tobytes())
        det_digest = det_digest_h.hexdigest()
        feature_digest = feature_digest_h.hexdigest()
        trackers = {}
        outputs_by_method = {}
        for method in methods:
            tracker = SimpleMOT(method, predictors.get(method), seed=args.seed, image_width=iw, image_height=ih)
            t0 = time.perf_counter(); outputs = tracker.run(det); elapsed = max(time.perf_counter() - t0, 1e-8)
            metrics = evaluate_mot(gt, outputs)
            trackers[method] = tracker; outputs_by_method[method] = outputs
            metric_frames = sorted(set(gt) | set(det))
            metrics.update({
                "frames": len(metric_frames),
                "gt_frames": len(gt),
                "det_frames": len(det),
                "frame_id_min": int(metric_frames[0]) if metric_frames else None,
                "frame_id_max": int(metric_frames[-1]) if metric_frames else None,
                "detections": sum(len(v) for v in det.values()),
                "pred_rows": len(output_rows(outputs)),
                "fps_tracker": len(metric_frames) / elapsed,
                "association_seconds": tracker.time_assoc,
                "mean_cost_margin": float(np.mean(tracker.cost_margins)) if tracker.cost_margins else None,
                "temporal_prediction_count": int(tracker.temporal_prediction_count),
                "quality_mean": float(np.mean(tracker.quality_values)) if tracker.quality_values else None,
                "uncertainty_mean": float(np.mean(tracker.uncertainty_values)) if tracker.uncertainty_values else None,
                "memory_gate_accept": int(tracker.memory_gate_accept),
                "memory_gate_reject": int(tracker.memory_gate_reject),
                "detector_recall_iou50": fixed_det_recall,
                "detector_digest": det_digest,
                "feature_digest": feature_digest,
            })
            for bname, bframes in bins.items():
                bm = subset_metrics(gt, outputs, bframes)
                metrics[f"{bname}_frames"] = bm["frames"]
                metrics[f"{bname}_idf1"] = bm["idf1"]
                metrics[f"{bname}_IDSW"] = bm["num_switches"]
                metrics[f"{bname}_HOTA_proxy"] = bm["HOTA_proxy"]
                metrics[f"{bname}_AssA_proxy"] = bm["AssA_proxy"]
            track_path = out_root / name / "tracks" / method / f"{seq_name}.txt"
            save_track_file(track_path, outputs)
            metrics["track_sha256"] = sha256_file(track_path)
            # Sequence/CSV rows are assembled after this hash is known.
            seq_summaries[seq_name][method] = metrics
            row = {"dataset": name, "sequence": seq_name, "method": method, **metrics}
            all_rows.append(row)
        # Compare candidate->track assignments against raw after all methods
        # have run.  This is a direct attribution audit, independent of GT.
        raw_map = {(fr, j): tid for fr, pairs in trackers.get("raw", SimpleMOT("raw", None)).assignment_pairs.items() for tid, j in pairs}
        for method in methods:
            if method == "raw":
                continue
            cur = {(fr, j): tid for fr, pairs in trackers[method].assignment_pairs.items() for tid, j in pairs}
            keys = set(raw_map) | set(cur)
            changed = sum(1 for k in keys if raw_map.get(k) != cur.get(k))
            total = max(len(keys), 1)
            seq_summaries[seq_name][method]["assignment_changed_count_vs_raw"] = int(changed)
            seq_summaries[seq_name][method]["assignment_changed_rate_vs_raw"] = float(changed / total)
            # Keep the flat CSV row in sync with the enriched sequence record.
            for row in reversed(all_rows):
                if row["sequence"] == seq_name and row["method"] == method:
                    row.update({"assignment_changed_count_vs_raw": int(changed), "assignment_changed_rate_vs_raw": float(changed / total)})
                    break
    # Macro average (each sequence equal weight) and micro-ish weighted sums
    summary: Dict[str, Dict[str, float]] = {}
    for method in methods:
        rows = [r for r in all_rows if r["method"] == method]
        keys = ["idf1", "mota", "motp", "num_switches", "num_false_positives", "num_misses", "precision", "recall", "HOTA_proxy", "AssA_proxy", "DetA_proxy", "fps_tracker", "mean_cost_margin", "quality_mean", "uncertainty_mean", "memory_gate_accept", "memory_gate_reject", "assignment_changed_rate_vs_raw", "detector_recall_iou50"]
        # ``None`` is used for intentionally undefined bins/controls; coerce
        # it to NaN before macro averaging so a single raw-control field does
        # not abort an otherwise valid run.
        summary[method] = {
            k: float(np.nanmean([np.nan if r.get(k, np.nan) is None else r.get(k, np.nan) for r in rows]))
            for k in keys
        }
    strict_temporal_methods = [m for m in methods if m in ("jepa_temporal", "no_teacher", "random_frozen")]
    legacy_methods = [m for m in methods if m.startswith("jepa_") and m not in ("jepa_temporal",)]
    protocol = {
        "teacher_gt_only": True,
        "student_context_gt": False,
        "gt_geometry_in_student": False,
        "gt_geometry_in_student_x": False,
        "gt_visibility_in_student": False,
        "strict_temporal_methods": strict_temporal_methods,
        "legacy_methods_candidate_conditioned": legacy_methods,
        "candidate_in_predictor": bool(legacy_methods),
        "predictor_api": "TemporalPredictor.predict(tokens) -> (latent, quality, log_variance)" if strict_temporal_methods else "legacy StudentPredictor",
        "temporal_k": TEMPORAL_K if strict_temporal_methods else None,
        "token_scalar_schema": ["age_dt", "center_x", "center_y", "scale_w", "scale_h", "velocity_x", "velocity_y", "detector_score", "missing_mask"] if strict_temporal_methods else None,
        "student_context_source": "K fixed-offset matched detector crops+observable boxes/scores/velocity; zero appearance+missing mask on absent frames",
        "current_corruption": ["feature_mask", "gaussian_noise", "identity_mix"],
        "association_negative": "same-frame fixed-detector candidate negative when available (label only)",
        "cross_time_target": "current and next-frame clean GT crop teacher labels (stop-gradient)",
        "uncertainty_gate": "quality>=0.35, sigmoid(log_variance)<=0.65, detector_score>=0.35, prior_misses<=4",
        "eval_uses_gt": False,
        "validation_stats_postfit_only": True,
    }
    return {"dataset": name, "detector": detector_meta, "train_sequences": train_names, "eval_sequences": [x[3]["sequence"] for x in eval_items], "train_samples": {k: int(v.shape[0]) for k, v in train_samples.items()}, "validation_samples": int(val_samples["x"].shape[0]), "predictor_stats": {k: (v.train_stats if v is not None else None) for k, v in predictors.items()}, "validation_stats": validation_stats, "training_protocol": protocol, "sequences": seq_summaries, "summary": summary, "rows": all_rows}


