                detector_meta = {"type": "local YOLOX boxes (fallback extraction; provenance not independently pinned)", "checkpoint": str(YOLOX_CKPT), "checkpoint_sha256": sha256_file(YOLOX_CKPT), "oracle_boxes": False, "feature_encoder": "frozen crop_feature(v1): 4x4 RGB + color/gray moments", "feature_encoder_script_sha256": sha256_file(Path(__file__))}
