    # strict temporal bundle; legacy modes remain available only for backward
    # compatibility and are never silently substituted for jepa_temporal.
    train_samples = temporal_train_samples if temporal_train_samples is not None else legacy_train_samples
    if train_samples is None:
        train_samples = {"x": np.zeros((0, temporal_input_dim()), np.float32), "y": np.zeros((0, 80), np.float32)}
    predictors: Dict[str, Optional[object]] = {"raw": None, "gated_ema": None, "history_ema": None, "candidate_only": None, "no_teacher": None, "random_frozen": None, "jepa_temporal": None}
    for method in methods:
        if method in ("history_ema", "candidate_only"):
            continue
        if method == "random_frozen":
            pred = TemporalPredictor(80, method, args.seed, 0, "cpu") if use_temporal else StudentPredictor(80, method, args.seed, 0, "cpu")
            pred.fit_random(); predictors[method] = pred; continue
        if method in ("jepa_temporal", "no_teacher") and temporal_train_samples is not None:
            pred = TemporalPredictor(80, method, args.seed, args.epochs, "cuda" if args.dance_device == "cuda" else "cpu")
