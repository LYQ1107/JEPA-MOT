def xywh_to_xyxy(box: Sequence[float]) -> np.ndarray:
    x, y, w, h = [float(v) for v in box[:4]]
    return np.asarray([x, y, x + max(0.0, w), y + max(0.0, h)], dtype=np.float32)


def xyxy_to_xywh(box: Sequence[float]) -> np.ndarray:
    x1, y1, x2, y2 = [float(v) for v in box[:4]]
    return np.asarray([x1, y1, max(0.0, x2 - x1), max(0.0, y2 - y1)], dtype=np.float32)


def box_iou(a: Sequence[float], b: Sequence[float]) -> float:
    ax1, ay1, ax2, ay2 = [float(v) for v in a[:4]]
    bx1, by1, bx2, by2 = [float(v) for v in b[:4]]
    ix1, iy1 = max(ax1, bx1), max(ay1, by1)
    ix2, iy2 = min(ax2, bx2), min(ay2, by2)
    iw, ih = max(0.0, ix2 - ix1), max(0.0, iy2 - iy1)
    inter = iw * ih
    aa = max(0.0, ax2 - ax1) * max(0.0, ay2 - ay1)
    bb = max(0.0, bx2 - bx1) * max(0.0, by2 - by1)
    return inter / max(aa + bb - inter, 1e-9)


def cosine(a: np.ndarray, b: np.ndarray) -> float:
    den = max(float(np.linalg.norm(a) * np.linalg.norm(b)), 1e-8)
    return float(np.dot(a, b) / den)


def normalize(v: np.ndarray, axis: int = -1) -> np.ndarray:
    n = np.linalg.norm(v, axis=axis, keepdims=True)
    return v / np.maximum(n, 1e-8)


